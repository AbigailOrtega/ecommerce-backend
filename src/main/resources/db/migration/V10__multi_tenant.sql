-- Existing rows become Marea's. The default is dropped right after, so a row the app forgets to
-- assign fails loudly instead of silently landing in Marea.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'cart_items', 'categories', 'coupons', 'order_items', 'orders', 'page_views',
        'pickup_availability', 'pickup_exceptions', 'pickup_locations', 'pickup_time_slots',
        'product_colors', 'product_sizes', 'product_variants', 'products', 'promo_banners',
        'promotions', 'reviews', 'shipping_config', 'shipping_methods', 'store_image',
        'store_info', 'tickets', 'users'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1', t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN tenant_id DROP DEFAULT', t);
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (tenant_id) REFERENCES tenants (id)',
                       t, 'fk_' || t || '_tenant');
        EXECUTE format('CREATE INDEX %I ON %I (tenant_id)', 'idx_' || t || '_tenant', t);
    END LOOP;
END $$;

-- Slugs, SKUs, coupon codes and e-mails only need to be unique within a store
ALTER TABLE categories DROP CONSTRAINT categories_slug_key;
ALTER TABLE categories ADD CONSTRAINT uk_categories_tenant_slug UNIQUE (tenant_id, slug);

ALTER TABLE coupons DROP CONSTRAINT coupons_code_key;
ALTER TABLE coupons ADD CONSTRAINT uk_coupons_tenant_code UNIQUE (tenant_id, code);

ALTER TABLE products DROP CONSTRAINT products_sku_key;
ALTER TABLE products ADD CONSTRAINT uk_products_tenant_sku UNIQUE (tenant_id, sku);
ALTER TABLE products DROP CONSTRAINT products_slug_key;
ALTER TABLE products ADD CONSTRAINT uk_products_tenant_slug UNIQUE (tenant_id, slug);

ALTER TABLE users DROP CONSTRAINT users_email_key;
ALTER TABLE users ADD CONSTRAINT uk_users_tenant_email UNIQUE (tenant_id, email);
