-- Multi-store platform: every store-owned row gets a tenant_id. Everything that exists today
-- belongs to Marea, created here as store #1, so the store keeps working unchanged.

CREATE TABLE tenants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug character varying(63) NOT NULL UNIQUE,
    name character varying(255) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    created_at timestamp(6) without time zone
);

-- Host names that serve a store: lower-case, no "www." (the app also tries without it), no port
CREATE TABLE tenant_domains (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain character varying(255) NOT NULL UNIQUE,
    tenant_id bigint NOT NULL REFERENCES tenants (id)
);

