-- Existing rows become Marea's. The default is dropped right after, so a row the app forgets to
-- assign fails loudly instead of silently landing in Marea.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'cart_items', 'categories', 'coupons', 'order_items', 'orders', 'page_views',
        'pickup_availability', 'pickup_exceptions', 'pickup_locations', 'pickup_time_slots',
        'product_colors', 'product_sizes', 'product_variants', 'products', 'promo_banners',
        'promotions', 'reviews', 'shipping_config', 'shipping_methods', 'store_image',
        'store_info', 'tickets', 'users'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1', t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN tenant_id DROP DEFAULT', t);
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (tenant_id) REFERENCES tenants (id)',
                       t, 'fk_' || t || '_tenant');
        EXECUTE format('CREATE INDEX %I ON %I (tenant_id)', 'idx_' || t || '_tenant', t);
    END LOOP;
END $$;

-- Slugs, SKUs, coupon codes and e-mails only need to be unique within a store. The old one-column
-- unique constraints are found by column, not by name: databases first built by Hibernate named
-- them uk_<hash>, the baseline <table>_<column>_key.
DO $$
DECLARE
    target record;
    c record;
BEGIN
    FOR target IN SELECT * FROM (VALUES
        ('categories', 'slug'), ('coupons', 'code'), ('products', 'sku'), ('products', 'slug'), ('users', 'email')
    ) AS v(tbl, col) LOOP
        -- unique constraints on exactly that column
        FOR c IN
            SELECT con.conname
            FROM pg_constraint con
            JOIN pg_class rel ON rel.oid = con.conrelid
            JOIN pg_namespace ns ON ns.oid = rel.relnamespace AND ns.nspname = current_schema()
            JOIN pg_attribute att ON att.attrelid = rel.oid AND att.attnum = con.conkey[1]
            WHERE con.contype = 'u' AND rel.relname = target.tbl
              AND array_length(con.conkey, 1) = 1 AND att.attname = target.col
        LOOP
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', target.tbl, c.conname);
        END LOOP;
        -- and plain unique indexes on it (not backing a constraint)
        FOR c IN
            SELECT idx.relname
            FROM pg_index i
            JOIN pg_class idx ON idx.oid = i.indexrelid
            JOIN pg_class rel ON rel.oid = i.indrelid
            JOIN pg_namespace ns ON ns.oid = rel.relnamespace AND ns.nspname = current_schema()
            JOIN pg_attribute att ON att.attrelid = rel.oid AND att.attnum = i.indkey[0]
            WHERE i.indisunique AND NOT i.indisprimary AND rel.relname = target.tbl
              AND i.indnatts = 1 AND att.attname = target.col
              AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.indexrelid)
        LOOP
            EXECUTE format('DROP INDEX %I', c.relname);
        END LOOP;
    END LOOP;
END $$;

